// ABOUTME: Claude's reading of every file: chooses the files (each one left out named with its reason), orders and packs them into
// ABOUTME: calls, runs the calls one at a time with what it was agreed to spend, and checks every reply against what was sent.
"use strict";

const { createHash, randomBytes } = require("crypto");
const {
  chunkFile, packChunks, estimateReading, readingPrompt, checkReading, READING_SCHEMA, READING_SYSTEM_PROMPT, READING_VERDICTS, FENCE_LENGTH,
} = require("../../lib/deep/reading");
const { claudeReviewArgs } = require("../../lib/deep/claudeArgs");
const { emptyClaudeUsage, addClaudeReply } = require("../../lib/deep/claudeUsage");
const { readCliReply } = require("../../lib/deep/cliReply");
const { scriptCapabilities, isRisky } = require("../../lib/scriptCapabilities");
const { redactSecrets } = require("../../lib/secretPatterns");
const { isLockfile } = require("./lockfiles");
const { runClaude, CLAUDE_TIMEOUT_MS } = require("./runClaude");

const LEFT_OUT_FOLDERS = new Set(["node_modules", "vendor", "dist", "build"]);
const GENERATED_MARKER = /@generated|auto-generated|autogenerated|do not edit/i;
const MINIFIED_LINE = 1000;
const QUOTE_MAX = 200;

const VENDORED = "vendored or build output";
const LOCKFILE = "lockfile, checked against OSV instead";
const GENERATED = "looks minified or generated";
const EMPTY = "empty, nothing to read";

const STOPPED = {
  missing: "the claude CLI is not installed",
  refused: "Claude declined to read part of it",
  limit: "Claude usage limit reached",
  failures: "two calls failed in a row",
  budget: "the token budget was reached",
};
const CALL_FAILED = "the call failed";
const NO_VERDICT = "Claude gave no verdict on part of it";
const NOT_REACHED = "not reached: the reading stopped";

const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

// Text from the target (paths, quotes) is shown with control and format characters replaced, so it cannot rewrite the output.
const printable = (text) => text.replace(/[\p{Cc}\p{Cf}]/gu, "?");

function leftOutReason(file) {
  if (file.path.split("/").slice(0, -1).some((segment) => LEFT_OUT_FOLDERS.has(segment))) return VENDORED;
  if (isLockfile(file.path)) return LOCKFILE;
  const lines = file.text.split(/\r?\n/);
  if (lines.slice(0, 50).some((line) => line.length > MINIFIED_LINE) || GENERATED_MARKER.test(lines.slice(0, 5).join("\n"))) return GENERATED;
  if (chunkFile(file).length === 0) return EMPTY;
  return null;
}

// installPaths: files that run or say what runs at install and start-up; agentPaths: files an agent loads.
function chooseForReading(files, { installPaths, agentPaths }) {
  const install = new Set(installPaths);
  const agent = new Set(agentPaths);
  const group = (f) => (isRisky(scriptCapabilities(f.text)) ? 0 : install.has(f.path) ? 1 : agent.has(f.path) ? 2 : 3);
  const reading = [];
  const leftOut = [];
  for (const f of files) {
    const reason = leftOutReason(f);
    if (reason) leftOut.push({ path: f.path, reason });
    else reading.push({ path: f.path, text: f.text, group: group(f) });
  }
  reading.sort((a, b) => a.group - b.group || compare(a.path, b.path));
  leftOut.sort((a, b) => compare(a.path, b.path));
  return { reading: reading.map(({ path, text }) => ({ path, text })), leftOut };
}

// The plan id here names exactly the text to be read; a repository's plan id is its commit instead.
function planReading(reading) {
  const calls = packChunks(reading.flatMap((f) => chunkFile(f)));
  const hash = createHash("sha256");
  for (const f of reading) hash.update(`${f.path}\0${f.text}\0`);
  return { calls, estimate: estimateReading(calls), planId: hash.digest("hex") };
}

const usedTokens = (u) => u.inputTokens + u.cacheWriteTokens + u.cacheReadTokens + u.outputTokens;

async function readEveryFile({ calls, model, budget = null, command, env = process.env, timeoutMs = CLAUDE_TIMEOUT_MS, run = runClaude }) {
  const args = claudeReviewArgs({ model, systemPrompt: READING_SYSTEM_PROMPT, schema: READING_SCHEMA });
  const usage = emptyClaudeUsage();
  const verdicts = [];
  const findings = [];
  const unread = new Map();
  const markUnread = (chunks, reason) => {
    for (const c of chunks) if (!unread.has(c.path)) unread.set(c.path, reason);
  };
  let dropped = 0;
  let failuresInRow = 0;
  let stopReason = null;
  let next = 0;
  while (next < calls.length) {
    const call = calls[next];
    if (budget !== null && usedTokens(usage) + estimateReading([call]).inputTokens > budget) {
      stopReason = STOPPED.budget;
      break;
    }
    const outcome = await run({ args, prompt: readingPrompt(call, randomBytes(FENCE_LENGTH / 2).toString("hex")), timeoutMs, command, env });
    if (outcome.missing) {
      stopReason = STOPPED.missing;
      break;
    }
    addClaudeReply(usage, outcome.stdout);
    const reply = outcome.timedOut ? { ok: false, error: "timed out" } : readCliReply(outcome.stdout);
    if (!reply.ok && reply.refused) {
      stopReason = STOPPED.refused;
      break;
    }
    if (!reply.ok && /usage limit|rate limit/i.test(reply.error)) {
      stopReason = STOPPED.limit;
      break;
    }
    next++;
    if (reply.ok) {
      failuresInRow = 0;
      const checked = checkReading(reply.output, call);
      verdicts.push(...checked.verdicts);
      findings.push(...checked.findings);
      dropped += checked.dropped;
      markUnread(checked.notRead, NO_VERDICT);
    } else {
      markUnread(call, CALL_FAILED);
      if (++failuresInRow === 2) {
        stopReason = STOPPED.failures;
        break;
      }
    }
    if (budget !== null && usedTokens(usage) > budget && next < calls.length) {
      stopReason = STOPPED.budget;
      break;
    }
  }
  for (const call of calls.slice(next)) markUnread(call, NOT_REACHED);

  const rank = (verdict) => READING_VERDICTS.indexOf(verdict);
  const worst = new Map();
  for (const v of verdicts) if (!worst.has(v.path) || rank(v.verdict) < rank(worst.get(v.path))) worst.set(v.path, v.verdict);
  const order = [...new Set(calls.flat().map((c) => c.path))];
  // A file only partly read is listed as read only when what was read is enough to flag it.
  const files = order
    .filter((p) => worst.has(p) && (!unread.has(p) || worst.get(p) !== "benign"))
    .map((p) => ({ path: p, verdict: worst.get(p) }));
  const notRead = order.filter((p) => unread.has(p)).map((p) => ({ path: p, reason: unread.get(p) }));
  return { status: stopReason ? "stopped" : "done", stopReason, files, findings, dropped, notRead, usage };
}

// The line Claude pointed at, from the file itself: trimmed, secrets redacted as the scanner redacts, made printable, cut short.
function quoteLine(text, line) {
  const own = text.split(/\r?\n/)[line - 1] ?? "";
  return Array.from(printable(redactSecrets(own.trim()))).slice(0, QUOTE_MAX).join("");
}

module.exports = { chooseForReading, planReading, readEveryFile, quoteLine, printable };
